function seedLaporanKeuangan(rts: Rt[], rws: Rw[]): LaporanKeuanganRt[] {
  const now = '2026-11-14T10:00:00';
  const rows: LaporanKeuanganRt[] = [];
  const last3Keys = new Set(
    DAOP_BULAN_SEED.slice(-3).map((p) => `${p.tahun}-${p.bulan}`),
  );

  for (const [i, rt] of rts.entries()) {
    // Pola demo: beberapa RT belum setor 3 bulan penuh → masuk daftar blast
    const streak3Belum = rt.id === 'rt-1' || rt.id === 'rt-7-2' || rt.id === 'rt-1-3';
    const sebagianBelum = rt.id === 'rt-3-1' || rt.id === 'rt-11-1';

    for (const [mi, periode] of DAOP_BULAN_SEED.entries()) {
      const pemasukan = 1_250_000 + i * 75_000 + mi * 25_000;
      const pengeluaran = 680_000 + i * 40_000 + mi * 15_000;
      const diJendelaBlast = last3Keys.has(`${periode.tahun}-${periode.bulan}`);
      let status: LaporanKeuanganRt['status'] = 'SUDAH_UPLOAD_TTD';

      if (streak3Belum && diJendelaBlast) {
        status = 'BELUM_SETOR';
      } else if (streak3Belum && !diJendelaBlast) {
        status = 'SUDAH_UPLOAD_TTD'; // arsip lama sudah lunas
      } else if (sebagianBelum && diJendelaBlast) {
        const idxLast = DAOP_BULAN_SEED.slice(-3).findIndex(
          (p) => p.tahun === periode.tahun && p.bulan === periode.bulan,
        );
        status = idxLast === 2 ? 'BELUM_SETOR' : idxLast === 1 ? 'SUDAH_CETAK' : 'SUDAH_UPLOAD_TTD';
      } else if (i % 3 === 0 && diJendelaBlast && periode.bulan === 10) {
        status = 'SUDAH_CETAK';
      }

      const sudahUpload = status === 'SUDAH_UPLOAD_TTD';
      const sudahCetak = status !== 'BELUM_SETOR';

      rows.push({
        id: `keu-${rt.id}-${periode.tahun}-${String(periode.bulan).padStart(2, '0')}`,
        kelurahanId: 'kel-1',
        tingkat: 'RT',
        rtId: rt.id,
        rwId: rt.rwId,
        periodeLabel: periode.label,
        tahun: periode.tahun,
        bulan: periode.bulan,
        jenis: 'DAOP',
        status,
        pemasukan,
        pengeluaran,
        saldo: pemasukan - pengeluaran,
        catatan: sudahUpload ? 'Laporan DAOP RT — sudah TTD Ketua RT & Bendahara' : undefined,
        scanFileName: sudahUpload
          ? `DAOP-${periode.label.replace(/\s+/g, '-')}-${rt.nomor}-TTD.pdf`
          : undefined,
        scanUploadedAt: sudahUpload ? '2026-11-10T09:30:00' : undefined,
        dicetakAt: sudahCetak ? '2026-11-08T14:00:00' : undefined,
        diuploadOleh: sudahUpload ? rt.namaKetua : undefined,
        caraSetor: sudahUpload ? 'UPLOAD_MANDIRI' : undefined,
        tenggatAt: periode.tenggatAt,
        createdAt: now,
        updatedAt: sudahUpload ? '2026-11-10T09:30:00' : sudahCetak ? '2026-11-08T14:00:00' : now,
      });
    }
  }

  // Kewajiban DAOP Ketua RW (terpisah dari RT)
  for (const [i, rw] of rws.entries()) {
    const streak3Belum = rw.id === 'rw-7'; // demo uji WA Ketua RW 07
    const sebagianBelum = rw.id === 'rw-1';

    for (const [mi, periode] of DAOP_BULAN_SEED.entries()) {
      const pemasukan = 2_500_000 + i * 100_000 + mi * 40_000;
      const pengeluaran = 1_100_000 + i * 50_000 + mi * 20_000;
      const diJendelaBlast = last3Keys.has(`${periode.tahun}-${periode.bulan}`);
      let status: LaporanKeuanganRt['status'] = 'SUDAH_UPLOAD_TTD';

      if (streak3Belum && diJendelaBlast) {
        status = 'BELUM_SETOR';
      } else if (streak3Belum && !diJendelaBlast) {
        status = 'SUDAH_UPLOAD_TTD';
      } else if (sebagianBelum && diJendelaBlast) {
        const idxLast = DAOP_BULAN_SEED.slice(-3).findIndex(
          (p) => p.tahun === periode.tahun && p.bulan === periode.bulan,
        );
        status = idxLast === 2 ? 'BELUM_SETOR' : 'SUDAH_UPLOAD_TTD';
      }

      const sudahUpload = status === 'SUDAH_UPLOAD_TTD';
      const sudahCetak = status !== 'BELUM_SETOR';

      rows.push({
        id: `keu-rw-${rw.id}-${periode.tahun}-${String(periode.bulan).padStart(2, '0')}`,
        kelurahanId: 'kel-1',
        tingkat: 'RW',
        rwId: rw.id,
        periodeLabel: periode.label,
        tahun: periode.tahun,
        bulan: periode.bulan,
        jenis: 'DAOP',
        status,
        pemasukan,
        pengeluaran,
        saldo: pemasukan - pengeluaran,
        catatan: sudahUpload ? 'Laporan DAOP RW — sudah TTD Ketua RW & Bendahara' : undefined,
        scanFileName: sudahUpload
          ? `DAOP-RW-${periode.label.replace(/\s+/g, '-')}-${rw.nomor}-TTD.pdf`
          : undefined,
        scanUploadedAt: sudahUpload ? '2026-11-10T09:30:00' : undefined,
        dicetakAt: sudahCetak ? '2026-11-08T14:00:00' : undefined,
        diuploadOleh: sudahUpload ? rw.namaKetua : undefined,
        caraSetor: sudahUpload ? 'UPLOAD_MANDIRI' : undefined,
        tenggatAt: periode.tenggatAt,
        createdAt: now,
        updatedAt: sudahUpload ? '2026-11-10T09:30:00' : sudahCetak ? '2026-11-08T14:00:00' : now,
      });
    }
  }

  return rows;
}

